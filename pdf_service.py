"""
AKIRA PDF Export Service (pdf_service.py)
Generates high-quality, accessible study sheets and revision summaries in PDF format.
Safe against unescaped XML/HTML entities and long summaries.
"""

import io
import html
from datetime import datetime
from reportlab.lib.pagesizes import letter
from reportlab.lib import colors
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    Table,
    TableStyle,
    HRFlowable,
)
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.enums import TA_CENTER, TA_LEFT


def safe_text(text: str) -> str:
    """Safely escape text for ReportLab XML/HTML parsing."""
    if not text:
        return ""
    return html.escape(str(text), quote=False)


def generate_study_pdf(article_data: dict) -> io.BytesIO:
    """
    Generate a formatted PDF study sheet from article data.
    Returns an in-memory BytesIO buffer containing the PDF binary.
    """
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        rightMargin=40,
        leftMargin=40,
        topMargin=36,
        bottomMargin=36,
    )

    styles = getSampleStyleSheet()

    # Custom accessible palette
    primary_color = colors.HexColor("#1A365D")  # Deep accessible navy
    accent_color = colors.HexColor("#2B6CB0")   # Slate blue
    highlight_bg = colors.HexColor("#EBF8FF")   # Soft accessible light blue
    dark_text = colors.HexColor("#1A202C")
    muted_text = colors.HexColor("#4A5568")

    header_style = ParagraphStyle(
        "HeaderStyle",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=20,
        leading=24,
        textColor=primary_color,
        alignment=TA_LEFT,
        spaceAfter=4,
    )

    subhead_style = ParagraphStyle(
        "SubheadStyle",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=13,
        leading=17,
        textColor=accent_color,
        spaceBefore=10,
        spaceAfter=6,
    )

    meta_style = ParagraphStyle(
        "MetaStyle",
        parent=styles["Normal"],
        fontName="Helvetica-Oblique",
        fontSize=9,
        leading=12,
        textColor=muted_text,
        spaceAfter=12,
    )

    summary_box_style = ParagraphStyle(
        "SummaryBoxStyle",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=10,
        leading=15,
        textColor=dark_text,
        backColor=highlight_bg,
        borderColor=accent_color,
        borderWidth=1,
        borderPadding=8,
        borderRadius=4,
        spaceAfter=12,
    )

    bullet_style = ParagraphStyle(
        "BulletStyle",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=10,
        leading=14,
        textColor=dark_text,
        leftIndent=15,
        spaceAfter=5,
    )

    card_term_style = ParagraphStyle(
        "CardTermStyle",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=10,
        leading=13,
        textColor=primary_color,
    )

    card_def_style = ParagraphStyle(
        "CardDefStyle",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=9,
        leading=13,
        textColor=dark_text,
    )

    story = []

    # Title & Branding Banner
    brand_text = "<b>AKIRA</b> — Accessible Knowledge & Information Retrieval Assistant"
    story.append(Paragraph(brand_text, ParagraphStyle("Brand", fontName="Helvetica", fontSize=9, textColor=accent_color)))
    story.append(Spacer(1, 4))

    title = article_data.get("title", "Study Notes")
    story.append(Paragraph(f"Study Guide: {safe_text(title)}", header_style))

    gen_time = datetime.now().strftime("%B %d, %Y - %I:%M %p")
    url = article_data.get("url", "https://en.wikipedia.org")
    meta_line = f"Generated by AKIRA | Topic: {safe_text(title)} | Source: {safe_text(url)} | Date: {gen_time}"
    story.append(Paragraph(meta_line, meta_style))
    story.append(HRFlowable(width="100%", thickness=1, color=accent_color, spaceAfter=10))

    # Executive Summary Section
    summary = article_data.get("summary", "No summary available.")
    story.append(Paragraph("1. Executive Summary (Audio Recap)", subhead_style))
    story.append(Paragraph(safe_text(summary), summary_box_style))

    # Key Bullet Takeaways
    takeaways = article_data.get("takeaways", [])
    if takeaways:
        story.append(Paragraph("2. Key High-Yield Takeaways", subhead_style))
        for bullet in takeaways:
            clean_b = f"&bull;&nbsp;&nbsp;{safe_text(bullet)}"
            story.append(Paragraph(clean_b, bullet_style))
        story.append(Spacer(1, 10))

    # Flashcards / Study Concepts
    flashcards = article_data.get("flashcards", [])
    if flashcards:
        story.append(Paragraph("3. Revision Flashcards & Concepts", subhead_style))
        card_data = [
            [
                Paragraph("<b>Concept / Question</b>", ParagraphStyle("Th1", fontName="Helvetica-Bold", fontSize=9, textColor=colors.white)),
                Paragraph("<b>Key Definition & Explanation</b>", ParagraphStyle("Th2", fontName="Helvetica-Bold", fontSize=9, textColor=colors.white)),
            ]
        ]
        for card in flashcards:
            term = card.get("term") or card.get("question") or "Concept"
            definition = card.get("definition") or card.get("answer") or ""
            card_data.append([
                Paragraph(f"<b>{safe_text(term)}</b>", card_term_style),
                Paragraph(safe_text(definition), card_def_style),
            ])

        card_table = Table(card_data, colWidths=[180, 350], repeatRows=1)
        card_table.setStyle(
            TableStyle([
                ("BACKGROUND", (0, 0), (-1, 0), primary_color),
                ("ALIGN", (0, 0), (-1, -1), "LEFT"),
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
                ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#CBD5E0")),
                ("TOPPADDING", (0, 0), (-1, -1), 6),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
                ("LEFTPADDING", (0, 0), (-1, -1), 8),
                ("RIGHTPADDING", (0, 0), (-1, -1), 8),
                ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#F7FAFC")]),
            ])
        )
        story.append(card_table)
        story.append(Spacer(1, 12))

    # Footer note
    footer_text = "AKIRA MCA Semester 3 Project — Accessible Knowledge & Information Retrieval Assistant."
    story.append(Spacer(1, 10))
    story.append(HRFlowable(width="100%", thickness=0.5, color=colors.HexColor("#E2E8F0"), spaceAfter=6))
    story.append(Paragraph(footer_text, ParagraphStyle("Footer", fontName="Helvetica", fontSize=8, textColor=muted_text, alignment=TA_CENTER)))

    doc.build(story)
    buffer.seek(0)
    return buffer
